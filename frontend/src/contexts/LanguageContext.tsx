export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    const stored = localStorage.getItem("gharpe-lang") as LangCode | null;
    if (stored && translations[stored]) setLangState(stored);
    setMounted(true);
  }, []);

  useEffect(() => {
    if (mounted) {
      localStorage.setItem("gharpe-lang", lang);
      document.documentElement.lang = lang === "en" ? "en" : lang === "hi" ? "hi" : lang === "bn" ? "bn" : lang === "mr" ? "mr" : "te";
    }
  }, [lang, mounted]);

  const setLang = useCallback((l: LangCode) => setLangState(l), []);

  const t = useCallback((key: string): string => {
    return translations[lang]?.[key] ?? translations.en[key] ?? key;
  }, [lang]);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within a LanguageProvider");
  return ctx;
}